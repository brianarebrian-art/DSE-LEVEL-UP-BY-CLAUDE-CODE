import withdrawn from './withdrawn.json'
import pendingReview from './pending-review.json'

/** `reason` is free text, or one of the codes in WITHDRAW_CODES. */
export interface WithdrawnEntry { date: string; reason: string }

/** subject → question id → entry. Edited by scripts/qbank/withdraw.mts. */
export const WITHDRAWN = withdrawn as Readonly<Record<string, Readonly<Record<string, WithdrawnEntry>>>>

// A code instead of a sentence: this file ships to every student's browser, and the
// same sentence repeated 597 times made it four times larger (2026-09-29).
export const WITHDRAW_CODES: Readonly<Record<string, string>> = {
  POSITIONAL_RATIONALE_REFERENCE:
    '解析以位置指稱選項（「第二項」「最後一項」「第三個選項」等）。選項每次呈現都會洗牌，這類字眼因此會指錯。' +
    '逐題改寫並經真人內容覆核後恢復（docs/rationale-repairs.md）。',
}

// Pending review (2026-09-30, UX loop 20; Yuna's hardening loop prompt §3): a question
// whose check could not decide whether it is sound is not shown until a person decides.
// Before this, the 13 class C questions of the positional-explanation check stayed live
// while they waited (docs/rationale-repairs.md §7). Kept apart from WITHDRAWN because the
// meaning differs: withdrawn = a known fault; pending = not yet known.
// pending-review.json is regenerated by `scripts/qbank/classify-posref.mts --write`
// (every class C row); posref-pending.test.mts checks the two agree.
export const PENDING_REVIEW = pendingReview as Readonly<Record<string, Readonly<Record<string, WithdrawnEntry>>>>

export const PENDING_CODES: Readonly<Record<string, string>> = {
  POSREF_AMBIGUOUS:
    '解析含「第二項」「最後一項」等字眼，機器判斷不到是指選項（會因洗牌而指錯）還是指內容。' +
    '等人手判斷後才決定恢復或收起（docs/rationale-repairs/posref-review-queue.md）。',
}

export const HIDDEN_TOPICS: Readonly<Record<string, readonly string[]>> = {
  'ethics-religious': ['religion_philosophy', 'religion_society'],
}

export function isHiddenTopic(subjectId: string, topicId: string): boolean {
  return HIDDEN_TOPICS[subjectId]?.includes(topicId) ?? false
}

export function isWithdrawn(subjectId: string, id: string): boolean {
  return !!WITHDRAWN[subjectId]?.[id]
}

export function isPendingReview(subjectId: string, id: string): boolean {
  return !!PENDING_REVIEW[subjectId]?.[id]
}

/**
 * Every authored question has exactly one status. Only `published` reaches students.
 * Order matters when two apply: a known fault (withdrawn) outranks a hidden topic,
 * which outranks an open question (pending review). The counts in CONTENT_STATS
 * (summary.generated.ts) use this function, so they add up to the total by construction.
 */
export type ContentStatus = 'published' | 'withdrawn' | 'withheld_topic' | 'pending_review'

export function contentStatus(subjectId: string, q: { id: string; topic: string }): ContentStatus {
  if (isWithdrawn(subjectId, q.id)) return 'withdrawn'
  if (isHiddenTopic(subjectId, q.topic)) return 'withheld_topic'
  if (isPendingReview(subjectId, q.id)) return 'pending_review'
  return 'published'
}

/** Keeps only published questions: drops withheld topics, withdrawn and pending-review questions. */
export function withoutWithheld<T extends { id: string; topic: string }>(subjectId: string, items: T[]): T[] {
  const hidden = HIDDEN_TOPICS[subjectId] ?? []
  const out = WITHDRAWN[subjectId] ?? {}
  const pending = PENDING_REVIEW[subjectId] ?? {}
  if (!hidden.length && !Object.keys(out).length && !Object.keys(pending).length) return items
  return items.filter((q) => contentStatus(subjectId, q) === 'published')
}
