//   ① 誘答必須互不相同【且代數上不恆等】。
//   ② 每個迴圈變數【必須出現在題幹】。
//   ③ 補量用值域寬的參數，不要用固定枚舉表。
//   ④ 迴圈相乘：三層各加一值即八倍，不是加三。
//   ⑤ 改完即量度。
//   ⑥ 模板組合空間見頂時，要加的是【模板】而不是取值。
//   ⑦ 英文動詞只可用三態相異的不規則動詞。
//   ⑧ 引用了迴圈變數【不等於】輸出會變 —— 佔位符必須每條都存在。
