// 學生背下去就是錯的。故本檔不憑記憶出題，一律採用兩種結構：
//
//   甲・自撰材料：詩句、語段、情境【全部由本檔撰寫】，
//       所以答案由我方寫下的材料唯一決定。手法是為了示範而寫的，
//       該手法就必然成立（correct-by-construction）。
//   乙・體制與方法：問的是文體體制（詞的上下片、曲的賓白科介、
//       章回體的回目）與鑑賞方法（意境怎樣分析、風格怎樣判斷）——
//       這些是可以清楚界定的規範，不是需要背誦的個別作品。
//
// 兩者都不要求學生記得「哪一句出自哪一篇」，而這正是本科評核的重心：
// 鑑賞能力是可遷移的，換一首沒讀過的詩仍然要答得出。
//
// ⚠️ 八條累積教訓（同日十三役）：
//   ① 誘答必須互不相同【且代數上不恆等】。
//   ② 每個迴圈變數【必須出現在題幹】。
//   ③ 補量用值域寬的參數，不要用固定枚舉表。
//   ④ 迴圈相乘：三層各加一值即八倍，不是加三。
//   ⑤ 改完即量度。
//   ⑥ 模板組合空間見頂時，要加的是【模板】而不是取值。
//   ⑦ 英文動詞只可用三態相異的不規則動詞。
//   ⑧ 引用了迴圈變數【不等於】輸出會變 —— 佔位符必須每條都存在。
// ═══════════════════════════════════════════════════════════════════════════

