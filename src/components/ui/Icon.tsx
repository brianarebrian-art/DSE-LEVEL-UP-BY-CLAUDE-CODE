export function Icon({
  name,
  size = 24,
  className = '',
  label,
  'aria-label': ariaLabel,
  ...props
}: IconProps) {
  const iconRenderer = ICONS[name]
  const accessibleLabel = label || ariaLabel

  if (!iconRenderer) {
    logIconRenderError(name)
    return null
  }

  const svgElement = iconRenderer({
    width: size,
    height: size,
    className: `icon svg-icon inline-block shrink-0 align-middle ${className}`.trim(),
    role: accessibleLabel ? 'img' : 'presentation',
    'aria-label': accessibleLabel,
    'aria-hidden': accessibleLabel ? undefined : true,
    ...props,
  })

  return svgElement
}

