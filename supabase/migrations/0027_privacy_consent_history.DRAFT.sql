-- DRAFT ONLY — not applied. Adds append-only policy consent history without
-- modifying or deleting the existing privacy_consents snapshot rows.
-- The legacy snapshot keeps its exact policy_version/consented_at values; this
-- history table starts with a backfill of that last stored version and records
-- future acceptances as separate policy-version rows.

create table if not exists public.privacy_consent_history (
  id               bigint generated by default as identity primary key,
  user_id          text        not null,
  policy_version   text        not null,
  scope_version    text        not null,
  decision         text        not null check (decision = 'granted'),
  consented_at     timestamptz not null,
  recorded_at      timestamptz not null default timezone('utc', now()),
  source           text        not null check (source in ('legacy_snapshot', 'new_acceptance')),
  constraint privacy_consent_history_user_version_unique unique (user_id, policy_version)
);

comment on table public.privacy_consent_history is
  'Append-only per-user privacy consent events. policy_version and scope_version identify the exact consent scope; no IP, user-agent, email or device data.';
comment on column public.privacy_consent_history.consented_at is
  'Original acceptance time. Legacy values are copied verbatim from privacy_consents; new values are written once.';
comment on column public.privacy_consent_history.scope_version is
  'Immutable identifier for the wording/scope shown to the user; initially equals policy_version.';

alter table public.privacy_consent_history enable row level security;
revoke all on public.privacy_consent_history from public, anon, authenticated;
grant select, insert, delete on public.privacy_consent_history to service_role;
revoke all on sequence public.privacy_consent_history_id_seq from public, anon, authenticated;
grant usage, select on sequence public.privacy_consent_history_id_seq to service_role;

-- Preserve the exact currently stored consent evidence; do not UPDATE or reinterpret it.
insert into public.privacy_consent_history
  (user_id, policy_version, scope_version, decision, consented_at, source)
select user_id, policy_version, policy_version, 'granted', consented_at, 'legacy_snapshot'
from public.privacy_consents
on conflict (user_id, policy_version) do nothing;

